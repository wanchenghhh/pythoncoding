"""
 复合赋值运算  就是在 =前面 加上 算数运算符
 += 将左边和右边进行相加，把结果赋值给左边的变量  
 -= 将左边和右边进行相减，把结果赋值给左边的变量
 *= 
 /= 
 //=
 %=
 **=  
 整体的规律就是 将左边和右边进行相应的计算,把运算的结果赋值给左边的变量   
"""
a = 8
b = 2
a **= b  # 两步操作 先进行  a**b 得到一个结果 再将结果赋值给a
print(a)
print(b)
