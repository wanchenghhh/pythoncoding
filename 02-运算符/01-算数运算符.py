"""
  讲解 算数运算符使用
"""

"""
  +  加号 
  -  减号
  *  乘号
  /  除法运算
  // 整除运算
  %  取余运算 
  ** 取幂运算  
  () 提高优先级 
"""
#1: 除
print(9/2) # 4.5

# 2:整除 保留整数部分
print(9//2) # 4

# 3 取余运算
print(9%2) # 1
print(8%2) # 0

# 4 取幂运算
print(2**10) # 1024    1GB = 1024MB   1MB=1024KB  1KB=1024B

# 5 ()
print((2+3)*10) # 50