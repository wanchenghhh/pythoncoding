"""

**案例需求**

求相邻元素最大值.编写一个程序，求一个正整数数组中每对相邻元素的最大值。
 例如, 输入: [7 8 9 5 6 7 2 3] 输出: [8, 9, 9, 6, 7, 7, 3]

       7 8 9 5 6 7 2 3
        8 9 9 6 7 7 3
 思考:
    1: 准备一个原列表 [7 8 9 5 6 7 2 3]
       准备一个新列表 空
    2: 遍历--for while 用哪一个？  用while 因为只有通过索引才知道 下一个元素
    3: 循环里面  两个元素 求较大值 存到 新列表中(追加)
    4: 循环做完  拿到结果 打印 新列表
"""
# 1：准备原列表 和 新列表
src_list = [7,8,9,5,6,7,2,3]
new_list = []
# 2 遍历原列表 索引从0 开始 到 len(原列表)-2 索引位置
i = 0
while i < len(src_list)-1:
    value = max(src_list[i],src_list[i+1]) # max 俩个数据取最大值
    # 存到新的列表中
    new_list.append(value)
    # 更新计数器
    i += 1
# 打印最终结果
print(new_list)