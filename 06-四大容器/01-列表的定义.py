"""
  列表:
     可以存储多个数据的容器,且在该容器中的数据可以发生变化,允许存储重复元素,这样的容器称为列表。
  特点:
     存储多个元素,可以修改元素
     里面的元素有索引!!
     可以存重复元素。
   定义语法
     可以定义空列表  []
   取元素的语法
   一维的列表
     列表[索引]
   二维的列表(列表嵌套)
     列表[第一层索引][第二层索引]


"""
# 1:定义空列表
list1 = []   #  <class 'list'>
list3 = list() #空列表 同上
# 2: 定义有元素的列表
list2 = [1,"a",3,True,3.13]
# 3: 元素有索引
print(list2[3])# True
print(list2[-1]) # 3.13
print(list2[1:3]) # 支持切片 切出来是一个新的列表 ['a', 3]

# 4: 列表里面可以是任意类型  那么可以是列表吗？
group1 = ['小蔡','阿桐','小于','老贾']
group2 = ['小王','小於','小亿','小曦']
class_list = [group1,group2]
#  想找到 小于
print(class_list[0][2])
# 想找到 小於
print(class_list[1][1])

