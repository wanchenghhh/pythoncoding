"""
  这里整理了 四种容器 常用 api 的介绍

     字符串 列表 元组 集合 字典
     for ... in ... 都适合

     while  只适合有索引的
        列表 字符串 元组
     列表 字符串 元素  可以使用切片表达式
"""
"""
一、列表（list）
    1. 定义
        空列表：[] 或 list() 
        非空列表：[元素1, 元素2, ...]
        元素可以是任意类型，可嵌套

    2. 核心特点
        有序（有下标索引，从0开始）        
        元素可变（可增、删、改）       
        元素可重复        
        支持 for 和 while 循环       
        元素类型可混装

    3. 常用方法
        操作	方法/语法	说明
        增	列表.append(元素)	末尾追加一个元素
            列表.extend(容器)	将容器中的元素逐个追加到末尾
            列表.insert(索引, 元素)	在指定索引位置插入元素 
        删	
            列表.pop()       弹出列表最右端元素(并返回该元素)
            列表.pop(索引)	弹出指定索引的元素（并返回该元素）
            del 列表[索引]	弹出指定索引元素
            列表.remove(元素)	删除第一个匹配的指定值（一次删一个）
            列表.clear()	清空所有元素
            del 列表	删除整个列表对象
        改	
            列表[索引] = 新值	修改指定索引的元素
            sort() 实现元素自然排序
            sort(reverse=True) 实现元素自然排序 倒序
            reverse() 实现元素的反转
            列表[::-1] 实现列表元素的反转
        查	
            列表[索引]	根据索引获取元素
            列表.count(元素)	统计指定元素出现次数
            列表.index(元素)	查找第一个匹配元素的索引（不存在报错）
            len(列表)	获取元素总个数
        其他
            列表1 + 列表2	合并两个列表（生成新列表）
            列表 * n	重复列表 n 次
            元素 in 列表	判断元素是否存在
               not in 

        其他	max(元组)、min(元组)、sum(元组)	求最大/最小/总和（元素需为数值）       

    4. 遍历方式
        for 变量 in 列表:（直接迭代元素）

        while 索引 < len(列表):（通过下标访问）
        for 索引 in range(列表长度): （通过下标访问）

二、元组（tuple）
    1. 定义
        空元组：()  tuple()
        非空元组：(元素1, 元素2, ...)
       注意：单元素元组必须加逗号，如 (1,)，否则会被解释为普通括号运算

    2. 核心特点
         有序（有下标索引）        
         不可变（不能增、删、改元素）      
         元素可重复        
         支持 for 和 while 循环     
         元素类型可混装

    3. 常用方法（文档列出的）
        操作	 
        查            
            方法/语法	               说明 	             
            元组[索引]	        根据索引获取元素
           元组.index(元素)	    查找第一个匹配元素的索引（不存在报错）
           元组.count(元素)	    统计指定元素出现次数
            len(元组)	         获取元素总个数
        其他	max(元组)、min(元组)、sum(元组)	求最大/最小/总和（元素需为数值）
        ⚠️ 没有 append、pop、remove、insert、clear 等修改方法。

    4. 遍历方式
         for 变量 in 元组:

         while 索引 < len(元组):

三、集合（set）
    1. 定义
        空集合：只能用 set()（{} 是空字典）
        非空集合：{元素1, 元素2, ...}

    2. 核心特点
        无序（无下标索引，不支持 while）
         元素自动去重（不重复）
         元素只能是不可变类型（整数、浮点数、布尔值、字符串、元组），不能放列表、字典、集合自身
       可变（可增删改）
       支持 for 循环

    3. 常用方法（文档列出的）
        操作	方法/语法	说明
        增	集合.add(元素)	添加一个元素（若已存在则无变化）
        删	集合.pop()	随机删除一个元素并返回
            集合.remove(元素)	删除指定元素（不存在报错）
            集合.clear()	清空所有元素
            del 集合	删除整个集合对象
        集合的 交集 并集 差集	

        查	len(集合)	获取元素总个数
        其他	元素 in 集合	判断元素是否存在
    4. 遍历方式
        仅 for 变量 in 集合:（因为无序无下标，不支持 while）

四、字典（dict）
    1. 定义
        空字典：{} 或 dict()
        非空字典：{key1: value1, key2: value2, ...}
        键（key）必须是不可变类型（整数、浮点数、布尔值、字符串、元组），且不能重复
        值（value）可以是任意类型，可重复

    2. 核心特点
        无序（无下标索引，不支持 while）
        以“键值对”形式存储
        键唯一（自动去重）
        可变（可增删改键值对）
        支持 for 循环（默认遍历键）

    3. 常用方法（文档列出的）
        操作	方法/语法	说明
        增	字典[新key] = value	添加新的键值对
        改	字典[旧key] = 新value	修改已有键的值
        删	字典.pop(key)	删除指定键的键值对（并返回对应的值）
            del 字典[key]	删除指定键的键值对
            字典.clear()	清空所有键值对
            del 字典	删除整个字典对象
        查	字典[key]	根据键获取值（键不存在报错 KeyError）
            字典.get(key)	根据键获取值（键不存在返回 None，不报错）
            len(字典)	获取键值对总个数
            字典.keys()	获取所有键（可转为列表）
            字典.values()	获取所有值（可转为列表）
            字典.items()	获取所有键值对，每个键值对封装为元组
            键名 in 字典 判断键在不在字典中 
               not in 
    4. 遍历方式
            for key in 字典: → 遍历键，再用 字典[key] 获取值

            for key, value in 字典.items(): → 直接拆包获取键和值（推荐）
       不支持 while

 全局函数--内置
  set(元组、列表、字符串、集合)  将序列变成set集合     实现去重
  list(元组、列表、字符串、集合)  将序列变成list列表   实现有序 --可以改 
  tuple(元组、列表、字符串、集合) 将序列变成tuple元组  实现有序 --不可改 
  sorted(元组、列表、字符串、集合) 实现数据容器的排序 最终变成list列表
  sum() max() min() len() 
  del 全局操作       
"""