"""
 字符串的访问
"""
"""
   什么是字符串:  
        由n个字符组成的一串文本 (n>=0)
   注意  字符串有如下特点
     字符串一旦形成 不能改变！！
     字符串 是一串有顺序的字符序列！！
     字符串中字符是有顺序的,因为顺序,我们就给字符串里面的每个字符 设计了一个角标--索引
     这个角标 从 0 开始 依次递增 最大索引是字符串长度-1

        i   t   h   e   i   m   a
        0   1   2   3   4   5   6
        -7 -6  -5  -4  -3   -2  -1  

   学习的知识点
     1:获取字符串的长度 len(字符串) 返回一个数值型的整数 表示字符串中字符的数量 也称长度
     2:获取字符串中指定位置的字符 通过索引获取
        字符串名[索引] 返回指定的一个字符信息
     3:索引还有一种表示方式  从右往左数 起始-1    
"""
str = "itheima"
len = len(str)
print(f'{str}的长度:{len}')  # itheima的长度:7
print(str[0])  # i
print(str[3])  # e
print(str[6])  # a
# print(str[8]) # IndexError: string index out of range 索引越界

print(str[-7])  # i
print(str[-4])  # e
print(str[-1])  # a

