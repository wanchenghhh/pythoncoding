"""
  字符串的定义
    什么是字符串:  
        由n个字符组成的一串文本 (n>=0)
    有三种方式 
      单引号引起来 
      双引号引起来
      三引号引起来 
"""
# 1:演示 字符串的定义
str1 = '小蔡睡的香'
str2 = ("鹅鹅鹅"
        "曲项向天歌 "
        "白毛浮绿水 "
        "红掌拨清波")

print(str1)
print(str2)
# 使用单引号或双引号的时候  不识别我们的回车键！！也就是无法原样保存文本
# 三引号就可以实现 文本原样输出 (包含可以识别回车为换行)
str3 = '''鹅鹅鹅
曲项向天歌
白毛浮绿水
红掌拨清波'''
print(str3)

# 2: 字符串 使用的时候  如果 文本 里面有引号怎么解决
# line = "张三说:"jacklove很水""  相同的引号嵌套就出错了 怎么解决呢
line = '张三说:"jacklove很阿水"'  # 单引号嵌套双引号  或者是 双引号嵌套单引号
print(line)
line2 = "张三说:\"jacklove很阿水\"" # 说明 里面的双引号是输出内容不是语法 在双引号前面加 转义字符 \  表示 这个引号是输出内容不是语法

# 3:字符串可以实现拼接  使用 + 符号 注意左右两边必须是字符串
str4 = str1+",他梦里梦到了:"+str2
print(str4)

# 字符串可以跟*n 表示多个字符串的拼接
print("="*30)