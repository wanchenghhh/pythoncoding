"""
 介绍一下字符串常用的其他方法
"""
"""
  字符串一旦定义不能发生改变，
  如果说 修改 字符串 其实是产生了新串！！
     replace(旧串,新串,替换几次) 用新串替换旧串 如果没有指定次数 默认替换所有
     split(分隔符) 根据指定分隔符进行分割字符串 变成若干个小字符串,这次小字符串会被收集到列表
     split(分隔符,切几刀) 根据指定分隔符进行分割字符串(传递第二个参数代表切几次) 变成若干个小字符串,这次小字符串会被收集到列表
     分隔符.join(存放字符串的容器) 是将 其他容器(列表 元组 集合)里面的字符串 拼接起来！
"""
str1 = "小蔡同学今天真的很高兴，因为小蔡中了大奖,大奖奖励小蔡一辆奔驰！"
str2 = str1.replace("小蔡","老贾")
str3 = str1.replace("小蔡","老贾",1)
print(str1)# 小蔡同学今天真的很高兴，因为小蔡中了大奖,大奖奖励小蔡一辆奔驰！
print(str2)# 老贾同学今天真的很高兴，因为老贾中了大奖,大奖奖励老贾一辆奔驰！
print(str3)# 老贾同学今天真的很高兴，因为小蔡中了大奖,大奖奖励小蔡一辆奔驰！

date_str = '2026-11-22'
# 把 年月日 切割出来
date_list = date_str.split('-')
print(type(date_list)) # <class 'list'>
print(date_list)# ['2026', '11', '22']

# join 是将 其他容器(列表 元组 集合)里面的数据 拼接起来！
fruit_list=['榴莲','蓝莓','猕猴桃','西瓜','葡萄']
fruit_str = ",".join(fruit_list)
print(fruit_str)