"""
  集合推导式和字典推导式
"""
"""
  把数据推到集合中，注意什么时候用 去重的时候用 
  集合名={表达式 for 变量 in 容器/数据范围 }
"""
nums = [-2,-1,-3,3,4,5,2,1]
#  求 上述 列表中元素的平方 存起来 并去重
set1 = { num**2 for num in nums}
print(set1) # {1, 4, 9, 16, 25}
"""
 把数据推到字典中  
   字典名={ k:v  for 变量 in 容器/数据范围}
   使用 字典推导式  求出 1-10 数字的平方
   键 数字  值 平方
   1:1 2:4 3:9 ...
"""
dict = { i:i**2 for i in range(1,11)}
print(dict)