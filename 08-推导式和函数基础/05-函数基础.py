"""
  函数的好处 
      提高代码复用性和可维护性   
   函数:  
      把一段代码(实现特定功能),可以重复使用的代码打包(封装)起来，给它起个名字。
      以后需要这个功能,就调用这个名字。
      函数是先定义后调用！！
   函数 是一个 榨汁机    

   函数定义格式:
     def 函数名(形式参数):
        函数体
        return 返回值
     解释:
      def 声明函数的关键字,告诉python ，我要定义一个函数
      函数名 就是一个名字 遵循规范就可以 小写加下划线
      () 放形式参数 定义的时候，只需写出参数的变量名，不用给具体值,形式上的参数，简称形参  
      : 语法规范 注意下面代码要缩进！
      函数体 函数里面要实现的功能
      return 代表了函数的结束 
             如果函数的功能需要返回结果的，必须写return 带要返回的数据
             如果函数的功能不需要返回结果，return可写可不写。
             会把结果返回调用者？

      定义函数 
          只是打包代码,此时代码不会执行。
      调用函数 --- 调用语法      
          执行代码
        完整调用格式:
          变量名 = 函数名(实际参数)  
          解释
            实际参数: 因为定义的时候参数是形式上的，没有具体的值，那么调用就应该给具体的值。
               实际参数都是由具体的值！ 
          还有简化格式 
             如果定义的时候没有形式参数 ，就不用传递实际参数
             如果定义的时候 没有写return 带返回值  调用的时候 就不用使用变量接收    


"""


def sum(a, b):
    c = a + b
    return c


def printHello():
    print("Hello")


# 调用sum函数
add = sum(3, 4)  # 赋值调用 完整调用格式
print(add)
# 函数每次调用都是独立的
print(sum(2, 34))

# 调用 printHello()
printHello()  # 直接调用