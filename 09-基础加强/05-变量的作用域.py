"""
  变量的作用域
"""
"""
  变量的作用域 讲的是 变量的作用范围！！

  在函数中,变量的作用域指的是,变量起作用的范围,分成两种变量 
    全局变量: 定义在函数外,整个python文件中都有效
    局部变量: 定义在函数内/形参也算,仅仅在指定函数中生效,出了当前函数就无法访问
"""
# 全局变量
m = 20


def fun():
    # 局部变量
    n = 10
    print(f'在函数中打印全局变量{m}')
    print(f'在函数中打印局部变量{n}')


def fun1():
    print(f'在函数中打印全局变量{m}')
    # print(f'在函数中打印局部变量{n}')


fun()
print(f'在函数外部打印全局变量{m}')
# print(f'在函数外部打印局部变量{n}') #  name 'n' is not defined

print("============如果全局变量 和 局部变量 名字一样  那么访问谁呢？===============")
"""
   在函数中 访问变量 遵循的是 就近原则
"""
num = 10


def fun2():
    num = 20  # 局部变量~
    print(f'num的值{num}')


fun2()

print("============我如果想在函数中 修改 全局变量的值该怎么做？===============")
name = '大聪明'


def fun3():
    # name = '小马云' # 因为我们可以在 局部位置定义局部变量 语法上认为这里的name 是 局部变量 不是全局变量
    # 修改大聪明的值 如果需要修改全局变量的值 需要提前声明 name是全局变量 这样它就不会把name当成局部的了
    global name  # name是全局变量
    name = '小马云'
    print(f'函数里面访问 name:{name}')


fun3()  # 先调用函数后查看
print(f'被函数修改的name的值:{name}')