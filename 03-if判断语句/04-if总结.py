"""
  if 表达判断 用于实现分支语句结构

  if 第一种格式 适合 只有一种情况
    if 条件判断语句:
       语句体
    满足条件就执行语句体

  if 第二种格式 适合 有两种情况
    if 条件判断语句:
       语句体1
    else:
       语句体2
    满足条件就执行语句体1 否则执行语句体2

  if 第三种格式 适合 有多种情况
     if 条件判断语句1:
       语句体1
     elif  条件判断语句2:
       语句体2
     ...
     else:
       语句体n+1

     执行流程 先判断条件1 真就执行语句1-结束  假 判断条件2 真-执行语句2 结束 ..假....都不满足 执行else

"""

