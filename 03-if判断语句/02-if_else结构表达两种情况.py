"""
 if..else结构
"""
"""
   if...else..表达两种情况选择  如果... 否则...
   
   格式:
     if 条件:
       语句1
     else:
       语句2
       
       
   执行流程 
     先进行条件的判断！！
     if的条件成立，执行语句1，不走else了。
     if的条件成立，执行else后面的语句2
     
     如果结果是True   执行语句1 
        结果是False  执行语句2      
"""

age = int(input('请输入您的年龄:'))

# 如果年龄>=18岁 可以上网 否则 劝回家
if age >= 18:
    print('满足18岁的要求，可以上网...')
else:
    print('小朋友,给你一块糖,赶紧回家吧...妈妈在等你...')

#这个是判断外的语句，和判断没关系，要执行
print('语句体外的内容，该怎么执行还怎么执行')