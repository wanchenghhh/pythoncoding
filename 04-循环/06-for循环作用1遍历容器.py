"""
  for循环作用一  遍历容器
    容器概念,就是 这个类型里面可以存储 多个数据！
      比如 列表
        list = [1,4,6,8]
        遍历 就是  依次从容器中 把元素 取出来！
      字符串是存储 字符的容器

    【非常重要】！！
    语法格式：
      for 临时变量 in 容器:     解释语法 容器 指的是 列表/字符串  in 关键字  临时变量 用来接收 遍历出来每个数据的变量
          重复的代码
"""
# 定义列表容器
list = [1,4,6,8]
# 定义 字符串容器
str = "abcd"
# 遍历列表
for num in list:
    # num作用: 完成  list里面每个数据的接收
    print(num)

for ch in str:
    print(ch)
