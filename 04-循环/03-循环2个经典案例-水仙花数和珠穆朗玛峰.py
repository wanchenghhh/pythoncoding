"""
思考题
    珠穆拉玛峰 山峰高度 8848.86米  
    有一张 足够大的纸！！！ 厚度是 0.1 毫米 
    请问 折叠多少次 可以达到或超过 珠峰的高度！！
    换而言之 只要 折叠后的高度 小于 珠峰高度 就继续 折叠
    使用 while 就是一个变形式！
    步骤 
      1:统一单位 
          everest = 8848860 
          paper  = 0.1 
      2:定义统计变量 次数
         times = 0 
      3: 纸张的厚度是发生变化的 
          paper_height     
      4: 折纸这件事是重复做的 用循环  
        不知道几次？
          知道什么时候折    paper_height <   EVEREST  
        循环里面 折纸  计数       
"""
# 1:统一单位 定义 珠峰高度 和纸张的厚度 不变的量！！常量
EVEREST= 8848860
PAPER= 0.1
# 定义统计变量 次数
times = 0
# 纸张现在的厚度
paper_height  = PAPER
# 写循环
while paper_height < EVEREST:# 只要厚度没有到珠峰 就折纸
    # 表达折纸
    paper_height *= 2
    # 记录次数
    times += 1

print(f'需要折{times}次,可以达到或超过珠峰高度:{paper_height//1000}米')


