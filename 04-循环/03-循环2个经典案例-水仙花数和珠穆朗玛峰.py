"""
    水仙花数 是一个三位数    范围 100-999
    水仙数  个位 十位 百位 立方和 等于 原数  条件
    打印出来所有的 水仙花数 并 统计 数量
"""
# 1: 定义统计变量  以及 初始条件
count = 0
num = 100
# 2:实现循环
while num < 1000:
    # 满足条件统计
    ge = num % 10
    shi = num // 10 % 10
    bai = num // 100 % 10
    # 计算立方和
    lifang = ge**3 + shi**3 + bai**3
    if lifang == num : # 找到水仙花数
        count += 1   # 数量+1 ===================================这里要记得，是写在if判断里面才对。
        print(num)  # 打印水仙花
    num += 1 # 继续下一个
# 3：循环结束 打印统计的结果
print(f'水仙花数有{count}个')

