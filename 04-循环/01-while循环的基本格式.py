"""
  讲解循环的基础语法 (可以变化的)
   step1: 定义1个计数器变量(记录次数/位置)   初始化动作 执行一次
   step2: 写1个while 条件 控制语句  
          一般来说循环条件是用来决定是否可以进入循环执行的条件语句, 
               举例: 跑10圈 初始变量 1  
               当跑的圈数小于等于10 
               就跑
               
          代码格式： while 循环条件: 
                          执行代码（符合条件就重复执行）           
   step3: 循环体语句: 就是 进入循环之后执行的代码 【计数器记得要更新】
        如果我们是根据 计数器的数值 来决定是否进入循环的话 ，那么循环体里面也需要对计数器进行更新
        
            举例: 跑圈  每跑完一圈 计数器+1   
"""

"""
while 条件:
       符合条件就重复执行
"""

# 循环执行 6次  print("零基础学ai,去这儿")

# 1:定义计数器
i = 0 #  初始化为0 表示 还没有开始打印 记录打印次数

# 2: 写while主体 循环条件
while i < 6 :  # 0 1 2 3 4 5

#3:执行循环内容
    print("零基础学ai,去这儿")
    # 打印一次就加一
    i += 1   #   i = i+1

print(i)#看一下一共执行了几次