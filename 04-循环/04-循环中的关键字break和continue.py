"""
   循环中的关键字
"""
"""
   循环中会用到的两个关键字 
      break: 运行时,遇到它, 终止当前的循环。
      continue: 运行时,遇到它, 中断这一次的循环,继续下一次。
"""
# 小老虎 吃包子 5 个包子
# 包子编号
i = 1
while i <=5 :
    # 遇到了一个情况  吃第三个包子的时候  发现包子有虫子  动作 掀桌子
    #                              发现包子有虫子  想起妈妈说不要浪费食物，这个不吃 继续吃下一个
    if i ==3 :
        print(f'第{i}个包子有虫子,不吃了')
        # 用continue 一定要加 更新计数器  否则 会停不下来
        i +=1
        continue  # 中断这一次循环,继续下一次
        # break  # 循环结束了
    print(f'小老虎正在吃第{i}个包子~~')
    i += 1

print("吃完上课")