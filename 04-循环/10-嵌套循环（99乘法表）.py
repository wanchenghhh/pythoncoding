"""
  99乘法表
     9行9列
     数--形

     9行9列 矩形
     9行9列 直角三角形
     转换成
       * 转换成 式子
"""
"""
   第一步 打印一个矩形 
     理解嵌套循环  
       外层 控制 行数
       内层 控制 列
      外层执行一次 内层执行一轮   
    对代码进行解读 
       i 从1到9  代表 第一行到第九行
       j 从1到9  代表 第一列到第九列
       end=' '  表示打印星星的时候不换行 而是用空格隔开
       print()  只是做了换行   
"""
for i in range(1, 10):  # 9行
    for j in range(1, 10):  # 9列
        print('*', end=' ')  # 每一列是一个*  打印每个列之后 输出空格 每个*之间是空格
    print()  # 只为了换行
print("=" * 100)
"""
  把矩形砍一半！！ 变成三角形 
   第1行   1 个星
   第2行   2 个星
   ...
   第9行   9 个星

   解读
     第 i 行 打印 i个星 
"""
for i in range(1, 10):  # 9行
    for j in range(1, i + 1):  # 第i行 打印 i 个星
        print('*', end=' ')  # 每一列是一个*  打印每个列之后 输出空格 每个*之间是空格
    print()  # 只为了换行
print("=" * 100)

"""
  把星换成式子 
    式子的样子 
      1*1=1
      1*2=2  2*2=4 
      1*3=3  2*3=6  3*3=9 

      被乘数是 i  
      乘数是  j 
"""
for i in range(1, 10):  # i被乘数
    for j in range(1, i + 1):  # j 是乘数
        print(f'{j}*{i}={i * j}', end='\t')  # 星变成式子  end 间隔用制表符
    print()  # 只为了换行
print("=" * 100)