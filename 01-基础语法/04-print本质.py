"""
   print() 将结果打印在控制台上,称为输出
      默认作用1 数据打印在控制台 ,
      默认作用2 在打印完数据自动打印换行符
   完整语法
     print(输出的内容,end='输出结束后 做的事情')
"""

# \n 转义字符 表示换行的意思
# \t 制表符 默认是占4个空格
#end=' ',结果有空格，并连成一行
print('静静')
print('静静',end='\n')  # \n 转义字符 表示换行的意思
print('学AI,就来黑马程序员',end='\t')# \t 制表符 默认是占4个空格
print('学AI,就来黑马程序员',end='\n')
print('静静',end=' ') #结果有空格，并连成一行
print('jinng')