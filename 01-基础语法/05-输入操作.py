"""
  什么是输入 
    简单来说 就是将外部数据 输入到程序里面 ，程序里面就需要接收外部输入的数据。
    输入函数
     input('提示信息') 
      执行之后 控制台出现了提示信息  在提示信息后面完成输入 
       如果你不输入 程序会阻塞
       录入之后 就会继续往下
     输入函数 录完完成之后是一个字符串信息！！！
     输入函数的结果其实是 str类型  
      两种方式 
        直接打印   
        使用一个变量去接收！！！推荐 
          变量 = input('提示信息')
"""

# 使用变量接收 键盘录入数据
name = input('请输入您的姓名:')
age = input('请输入您的年龄:')

print(f'姓名:{name},年龄:{age}')

print(f'name的类型:{type(name)}')  # name的类型:<class 'str'>
print(f'age的类型:{type(age)}')  # age的类型:<class 'str'>