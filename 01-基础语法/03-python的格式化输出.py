"""
  python格式化输出
"""
"""
   输出:
     print() 将结果打印在控制台上,称为输出 
      默认作用1 数据打印在控制台 
      默认作用2 在打印完数据自动打印换行符、

   Python中输出语句的写法:
     默认支持格式:  print(变量名1,变量名2)   
     格式化: 采用% 占位符方式  
        格式化1 采用% 占位符方式  %s-->占字符串位置 %d-->占整数位置 %f->小数占位
             语法特点 格式化效果  %  真实数据
        格式化2 format() 函数完成格式化  特点 使用{} 代替了 %  
        格式化3 简化格式化2  f-string 

"""
# 定义几个变量
name = '徐坤·蔡'
age = 32
height = 1.846521
stu_id = 123

# 默认把四个信息打印出来
print(name, age, height, stu_id)
# 字符串和字符串之间 如果使用+ 表示拼接操作
# 字符串不能与数值类型 使用+号
# print("姓名:"+name,"年龄:"+age,height,stu_id)

# 格式化1 采用% 占位符方式  %s-->占字符串位置 %d-->占整数位置 %f->小数占位
# 语法特点 格式化效果  %  真实数据
print('姓名: %s, 年龄: %d, 身高: %f, 学号: %d' % (name, age, height, stu_id))
#  格式化细节  细节1 给小数保留指定位数 语法 %.nf n是小数点位数
#            细节2 整数类型进行补位   %nd n补的位数  数字占5个位置 不足的前面补空格
#                                 %0nd n补的位数  数字占5个位置 不足的前面补0
print('姓名: %s, 年龄: %d, 身高: %.2f, 学号: %5d' % (name, age, height, stu_id))
print('姓名: %s, 年龄: %d, 身高: %.2f, 学号: %05d' % (name, age, height, stu_id))

print(100 * '=')

# 格式化2 format() 函数完成格式化  特点 使用{} 代替了 %
print('姓名: {}, 年龄: {}'.format(name, age))

print(100 * '=')


#  f-string  掌握
#注意：格式化细节  细节1 给小数保留指定位数 语法 %.nf n是小数点位数
#            细节2 整数类型进行补位   %nd n补的位数  数字占5个位置 不足的前面补空格
#                                 %0nd n补的位数  数字占5个位置 不足的前面补0
print(f'姓名: {name}, 年龄: {age}')
print(f'姓名: {name}, 年龄: {age}, 身高: {height}, 学号: {stu_id}')
print(f'姓名: {name}, 年龄: {age}, 身高: {height:.2f}, 学号: {stu_id:05d}')


